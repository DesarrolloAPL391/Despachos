set lock_timeout = '5s';

-- ---------------------------------------------------------------------------------------------
-- 1) Las reglas
-- ---------------------------------------------------------------------------------------------
create table if not exists public.cartera_consigna_por (
  id          bigint generated by default as identity primary key,
  pagador     text check (pagador ~ '^[0-9]{5,12}$'),          -- la cédula con la que entra al banco
  conductor   text not null check (conductor ~ '^[0-9]{5,12}$'),  -- a quién se le abona
  recaudo_id  bigint references public.recaudos_banco (id) on delete cascade,  -- null = regla general
  desde       date,
  hasta       date,
  nota        text check (char_length(nota) <= 300),
  creado_en   timestamptz not null default now(),
  creado_por  uuid default auth.uid(),
  constraint ccp_regla_o_deposito check (recaudo_id is not null or pagador is not null),
  constraint ccp_no_a_si_mismo check (pagador is distinct from conductor),
  constraint ccp_fechas_solo_regla check (recaudo_id is null or (desde is null and hasta is null)),
  constraint ccp_orden check (desde is null or hasta is null or desde <= hasta)
);
create unique index if not exists ccp_deposito_uk on public.cartera_consigna_por (recaudo_id) where recaudo_id is not null;
create unique index if not exists ccp_regla_uk on public.cartera_consigna_por (pagador, (coalesce(desde, date '1900-01-01')))
  where recaudo_id is null;
create index if not exists ccp_pagador_idx on public.cartera_consigna_por (pagador) where recaudo_id is null;

alter table public.cartera_consigna_por enable row level security;
revoke all on public.cartera_consigna_por from anon, authenticated;

comment on table public.cartera_consigna_por is
  'Quien consigna por quien (sql/203): regla por cedula del banco o un deposito puntual -> conductor al que se le abona. Solo por las funciones consigna_por_*.';

-- ---------------------------------------------------------------------------------------------
-- 2) Cada depósito del banco con la cédula a la que se le abona
--    como: PROPIO (la del banco) · REGLA · ASIGNADO. regla = id de la regla que lo movió.
-- ---------------------------------------------------------------------------------------------
create or replace function public._recaudos_cartera(p_desde date)
returns table (id bigint, fecha date, valor bigint, banco text, archivo text, ref1 text,
               pagador text, ced text, como text, regla bigint)
language sql stable security definer set search_path to 'public'
as $function$
  select r.id, r.fecha, r.valor, r.banco, r.archivo, r.ref1, r.cedula,
         coalesce(e.conductor, g.conductor, r.cedula),
         case when e.id is not null then 'ASIGNADO' when g.id is not null then 'REGLA' else 'PROPIO' end,
         coalesce(e.id, g.id)
    from public.recaudos_banco r
    left join public.cartera_consigna_por e on e.recaudo_id = r.id
    left join lateral (
      select a.id, a.conductor from public.cartera_consigna_por a
       where a.recaudo_id is null and a.pagador = r.cedula
         and (a.desde is null or a.desde <= r.fecha) and (a.hasta is null or a.hasta >= r.fecha)
       order by a.desde desc nulls last, a.id desc
       limit 1) g on e.id is null
   where r.fecha > p_desde
$function$;
revoke all on function public._recaudos_cartera(date) from public, anon, authenticated;

-- ---------------------------------------------------------------------------------------------
-- 3a) _cartera_movs (sql/154) con la cédula a la que se le abona. Lo único distinto: "rb".
-- ---------------------------------------------------------------------------------------------
create or replace function public._cartera_movs(p_desde date, p_ced text default null, p_extra jsonb default null)
returns table (cedula text, clase text, ref text, fecha date, movil text, ruta text,
               valor bigint, estado text, ini bigint, fin bigint)
language sql stable security definer set search_path to 'public'
as $function$
  with x as (
    select (p_extra ->> 'fecha')::date as fecha, (p_extra ->> 'valor')::bigint as valor
     where p_ced is not null and p_extra is not null and (p_extra ->> 'valor') is not null
  ),
  cargos as (
    select l.conductor_cedula as ced, l.key as ref, l.fecha, l.movil, l.ruta, l.dinero as valor
      from public.liquidaciones l
     where l.fecha >= p_desde and l.dinero > 0 and coalesce(l.conductor_cedula, '') <> ''
       and (p_ced is null or l.conductor_cedula = p_ced)
  ),
  col as (
    select c.cedula as ced, c.id, c.fecha, c.movil, c.valor, c.banco, c.creado_en
      from public.liq_colillas c
     where c.fecha > p_desde and (p_ced is null or c.cedula = p_ced)
  ),
  -- Los depósitos del banco con la cédula a la que se le abonan (sql/203: quién consigna por quién)
  rb as (
    select b.id, b.fecha, b.valor, b.ced
      from public._recaudos_cartera(p_desde) b
     where b.valor > 0 and coalesce(b.ced, '') <> ''
  ),
  ban as (   -- consignaciones del extracto que NO son una colilla (enviada o la que se revisa)
    select rb.ced, rb.id, rb.fecha, rb.valor
      from rb
     where (p_ced is null or rb.ced = p_ced)
       and not exists (select 1 from public.liq_colillas c
                        where c.cedula = rb.ced and c.valor = rb.valor
                          and rb.fecha between c.fecha and c.fecha + 1)
       and not exists (select 1 from x where x.valor = rb.valor and rb.fecha between x.fecha and x.fecha + 1)
  ),
  abonos as (
    select col.ced, 'colilla'::text as clase, col.id::text as ref, col.fecha, col.movil, col.valor,
           case when exists (select 1 from rb
                              where rb.ced = col.ced and rb.valor = col.valor
                                and rb.fecha between col.fecha and col.fecha + 1) then 'CONFIRMADA'
                -- NO_APARECE solo si ya está el extracto de ESE banco del día y del siguiente
                when public._banco_clave(col.banco) is not null
                 and exists (select 1 from public.recaudos_banco r where r.fecha = col.fecha
                                and public._banco_clave(r.banco) = public._banco_clave(col.banco))
                 and exists (select 1 from public.recaudos_banco r where r.fecha = col.fecha + 1
                                and public._banco_clave(r.banco) = public._banco_clave(col.banco)) then 'NO_APARECE'
                else 'POR_CONFIRMAR' end as estado,
           col.creado_en as orden
      from col
    union all
    select ban.ced, 'banco', ban.id::text, ban.fecha, null, ban.valor, 'BANCO', ban.fecha::timestamptz from ban
    union all
    select p_ced, 'nueva', 'nueva', x.fecha, null, x.valor, 'NUEVA', 'infinity'::timestamptz from x
  )
  select ced, 'cargo', ref, fecha, movil, ruta, valor, null::text,
         sum(valor) over w - valor, sum(valor) over w
    from cargos
  window w as (partition by ced order by fecha, movil, ruta, ref rows unbounded preceding)
  union all
  select ced, clase, ref, fecha, movil, null, valor, estado,
         sum(valor) over w - valor, sum(valor) over w
    from abonos
  window w as (partition by ced order by fecha, orden, ref rows unbounded preceding)
$function$;
revoke all on function public._cartera_movs(date, text, jsonb) from public, anon, authenticated;

-- ---------------------------------------------------------------------------------------------
-- 3b) La planilla (sql/148) con la misma cédula: "con" y "banco_otros". Cada consignación dice
--     además quién la hizo cuando no fue el conductor (pagador).
-- ---------------------------------------------------------------------------------------------
create or replace function public.liquidaciones_planilla(
  p_desde date default null,
  p_hasta date default null,
  p_punto text default null,
  p_movil text default null
) returns jsonb
language plpgsql stable security definer set search_path to 'public'
as $function$
declare
  v_h date := coalesce(p_hasta, (now() at time zone 'America/Bogota')::date);
  v_d date := coalesce(p_desde, v_h - 30);
  -- Se consigna al otro día, a veces dos o tres días después (fines de semana): la ventana
  -- del banco se abre una semana a cada lado para no dejar pagos sin su liquidación.
  v_margen int := 7;
  v_out jsonb;
begin
  if not (select public.es_admin()) then
    return jsonb_build_object('ok', false, 'error', 'Solo el administrador.');
  end if;
  if v_h - v_d > 180 then
    return jsonb_build_object('ok', false, 'error', 'El rango no puede pasar de 180 días.');
  end if;

  with liq as (
    select l.*,
           nullif(regexp_replace(coalesce(l.conductor_cedula, ''), '[^0-9]', '', 'g'), '') as ced
      from public.liquidaciones l
     where l.fecha between v_d and v_h
       and (p_punto is null or btrim(p_punto) = '' or l.punto = btrim(p_punto))
       and (p_movil is null or btrim(p_movil) = '' or l.movil = btrim(p_movil))
  ),
  ceds as (select distinct ced from liq where ced is not null),
  filas as (
    select l.key, l.fecha, l.movil, l.ruta, l.punto, l.viajes,
           l.conductor, l.conductor_cedula, l.ced, l.propietario,
           l.unidades, l.descontar, l.total_liquidar, l.liquidar, l.dinero, l.cuadra,
           t.tarifa, t.valor as tarifa_valor
      from liq l
      left join lateral public._liq_tarifa(l.ruta, l.movil, l.fecha) t on true
  ),
  -- Lo que el mismo conductor liquidó la semana antes del rango: lo que consigna el día 1
  -- normalmente es de esos días, y sin ellos se lo cobraría a la primera fila del mes.
  previas as (
    select l.key, l.fecha, nullif(regexp_replace(coalesce(l.conductor_cedula, ''), '[^0-9]', '', 'g'), '') as ced,
           l.dinero
      from public.liquidaciones l
     where l.fecha between v_d - v_margen and v_d - 1
       and nullif(regexp_replace(coalesce(l.conductor_cedula, ''), '[^0-9]', '', 'g'), '') in (select ced from ceds)
       and (p_punto is null or btrim(p_punto) = '' or l.punto = btrim(p_punto))
  ),
  -- Y lo que liquidó la semana DESPUÉS: quien consigna el 15 lo del 14 y lo del 15 junto, en
  -- una planilla que termina el 14 saldría "pagó de más" si lo del 15 no estuviera en la cuenta.
  posteriores as (
    select l.key, l.fecha, nullif(regexp_replace(coalesce(l.conductor_cedula, ''), '[^0-9]', '', 'g'), '') as ced,
           l.dinero
      from public.liquidaciones l
     where l.fecha between v_h + 1 and v_h + v_margen
       and nullif(regexp_replace(coalesce(l.conductor_cedula, ''), '[^0-9]', '', 'g'), '') in (select ced from ceds)
       and (p_punto is null or btrim(p_punto) = '' or l.punto = btrim(p_punto))
  ),
  -- El banco con la cédula a la que se le abona (sql/203): si otra persona consignó por el conductor,
  -- el depósito llega con la cédula del conductor y "pagador" dice quién lo hizo.
  rb as (select * from public._recaudos_cartera(v_d - v_margen - 1)),
  con as (
    select rb.id, rb.ced, rb.fecha, rb.valor, rb.banco, rb.archivo,
           case when rb.como <> 'PROPIO' then rb.pagador end as pagador
      from rb
     where rb.ced in (select ced from ceds)
       and rb.fecha between v_d - v_margen and v_h + v_margen
  )
  select jsonb_build_object(
    'ok', true,
    'desde', v_d, 'hasta', v_h, 'punto', p_punto, 'margen', v_margen,
    'total', (select count(*) from filas),
    'resumen', jsonb_build_object(
      'dinero',     (select coalesce(sum(dinero), 0) from filas),
      'pax',        (select coalesce(sum(unidades), 0) from filas),
      'sin_cuadrar', (select count(*) filter (where not cuadra) from filas),
      'sin_tarifa',  (select count(*) filter (where tarifa is null) from filas),
      'rutas_sin_tarifa', (select coalesce(jsonb_agg(distinct ruta), '[]'::jsonb) from filas where tarifa is null),
      -- Lo que entró al banco en el rango de personas que NO aparecen en esta liquidación
      -- (otra flota, CENTRO, abonos de deudas): no se cruza, pero se dice cuánto es.
      'banco_rango', (select coalesce(sum(r.valor), 0) from public.recaudos_banco r
                       where r.fecha between v_d and v_h + 1),
      'banco_otros', (select coalesce(sum(rb.valor), 0) from rb
                       where rb.fecha between v_d and v_h + 1
                         and (rb.ced is null or rb.ced not in (select ced from ceds))),
      'banco_otros_personas', (select count(distinct coalesce(rb.ced, rb.ref1)) from rb
                       where rb.fecha between v_d and v_h + 1
                         and (rb.ced is null or rb.ced not in (select ced from ceds)))),
    'filas', (select coalesce(jsonb_agg(to_jsonb(f) order by f.fecha, f.movil, f.ruta), '[]'::jsonb) from filas f),
    'previas', (select coalesce(jsonb_agg(to_jsonb(p) order by p.fecha, p.key), '[]'::jsonb) from previas p),
    'posteriores', (select coalesce(jsonb_agg(to_jsonb(p) order by p.fecha, p.key), '[]'::jsonb) from posteriores p),
    'consignaciones', (select coalesce(jsonb_agg(to_jsonb(c) order by c.fecha, c.id), '[]'::jsonb) from con c),
    -- Días que tienen extracto cargado: sin extracto no se puede decir que alguien no pagó.
    'dias_banco', (select coalesce(jsonb_agg(distinct r.fecha order by r.fecha), '[]'::jsonb)
                     from public.recaudos_banco r
                    where r.fecha between v_d - v_margen and v_h + v_margen)
  ) into v_out;
  return v_out;
end $function$;
revoke all on function public.liquidaciones_planilla(date, date, text, text) from public, anon;
grant execute on function public.liquidaciones_planilla(date, date, text, text) to authenticated;

-- ---------------------------------------------------------------------------------------------
-- 4) El detalle de un conductor (sql/155) + quién consignó por él y qué depósitos suyos se pasaron
--    a otro. Solo administrador.
-- ---------------------------------------------------------------------------------------------
create or replace function public.cartera_conductor(p_cedula text)
returns jsonb
language plpgsql stable security definer set search_path to 'public'
as $function$
declare
  v_ced text := regexp_replace(coalesce(p_cedula, ''), '\D', '', 'g');
  v_desde date := public._cartera_desde();
  v_hoy date := (now() at time zone 'America/Bogota')::date;
  v_plazo int := coalesce((select c.plazo_dias from public.liq_cartera_config c where c.id), 1);
  v jsonb;
begin
  if not (select public.es_admin()) then
    return jsonb_build_object('ok', false, 'error', 'Solo el administrador.');
  end if;
  v := public._cartera(v_ced);
  if not coalesce((v ->> 'ok')::boolean, false) then return v; end if;
  return v || jsonb_build_object('cedula', v_ced, 'nombre', public._cartera_nombre(v_ced),
    'sin_liquidaciones', jsonb_array_length(v -> 'cargos') = 0, 'plazo', v_plazo,
    'puntual', (select coalesce(jsonb_agg(jsonb_build_object('key', k.ref, 'pagado_el', k.pagado_el, 'dias', k.dias,
                                 'a_tiempo', k.a_tiempo, 'prueba', k.prueba)), '[]'::jsonb)
                  from public._cartera_cumple(v_desde, v_hoy, v_plazo, v_ced) k),
    -- Depósitos del banco que hizo OTRA persona y se le abonan a él: { "<id del depósito>": {...} }
    'terceros', (select coalesce(jsonb_object_agg(b.id::text, jsonb_build_object(
                    'cedula', b.pagador, 'nombre', public._cartera_nombre(b.pagador), 'como', b.como)), '{}'::jsonb)
                   from public._recaudos_cartera(v_desde) b
                  where b.ced = v_ced and b.como <> 'PROPIO'),
    -- Depósitos con SU cédula que se le abonan a otro conductor
    'cedidos', (select coalesce(jsonb_agg(jsonb_build_object('id', b.id, 'fecha', b.fecha, 'valor', b.valor,
                    'a', b.ced, 'nombre', public._cartera_nombre(b.ced), 'como', b.como) order by b.fecha, b.id), '[]'::jsonb)
                   from public._recaudos_cartera(v_desde) b
                  where b.pagador = v_ced and b.ced is distinct from v_ced));
end $function$;
revoke all on function public.cartera_conductor(text) from public, anon;
grant execute on function public.cartera_conductor(text) to authenticated;

-- ---------------------------------------------------------------------------------------------
-- 5) Para la pantalla
-- ---------------------------------------------------------------------------------------------
-- Las personas que consignan sin tener liquidaciones desde el arranque (su plata no paga nada), con
-- sus depósitos que todavía nadie movió, qué son en la empresa y una sugerencia: el conductor con
-- días pendientes del MISMO valor entre 0 y 4 días antes de cada depósito (el que más coincide).
create or replace function public._consigna_personas(p_desde date, p_hoy date, p_plazo int, p_sugerir boolean default true)
returns jsonb
language sql stable security definer set search_path to 'public'
as $function$
  with dep as (
    select b.id, b.fecha, b.valor, b.pagador as ced
      from public._recaudos_cartera(p_desde) b
     where b.como = 'PROPIO' and b.valor > 0 and coalesce(b.pagador, '') <> ''
       and not exists (select 1 from public.liquidaciones l where l.conductor_cedula = b.pagador and l.fecha >= p_desde)
  ),
  pend as (
    select k.cedula, k.fecha, k.valor, k.valor - k.pagado as falta
      from public._cartera_cumple(p_desde, p_hoy, p_plazo) k
     where p_sugerir and k.pagado < k.valor
  ),
  cand as (
    select d.ced as pagador, d.id, p.cedula as conductor
      from dep d join pend p on (p.falta = d.valor or p.valor = d.valor) and p.fecha between d.fecha - 4 and d.fecha
     group by d.ced, d.id, p.cedula
  ),
  sug as (
    select c.pagador, c.conductor, count(*) as n,
           row_number() over (partition by c.pagador order by count(*) desc, c.conductor) as rk
      from cand c group by c.pagador, c.conductor
  ),
  per as (
    select d.ced, count(*) as n, sum(d.valor)::bigint as total, min(d.fecha) as primero, max(d.fecha) as ultimo,
           jsonb_agg(jsonb_build_object('id', d.id, 'fecha', d.fecha, 'valor', d.valor) order by d.fecha, d.id) as depositos
      from dep d group by d.ced
  )
  select coalesce(jsonb_agg(jsonb_build_object(
           'cedula', per.ced, 'nombre', public._cartera_nombre(per.ced),
           'n', per.n, 'total', per.total, 'primero', per.primero, 'ultimo', per.ultimo, 'depositos', per.depositos,
           'perfil', (select jsonb_build_object('estado', s.estado, 'cargo', s.cargo, 'area', s.area)
                        from public.perfilsociodemografico s where s.cedula = per.ced limit 1),
           'duenio_de', (select jsonb_agg(a.numero_interno::text order by a.numero_interno::text) from public.parque_automotor a
                          where regexp_replace(coalesce(a.identificacion, ''), '\D', '', 'g') = per.ced),
           'sugerencias', (select coalesce(jsonb_agg(jsonb_build_object('conductor', s.conductor,
                              'nombre', public._cartera_nombre(s.conductor), 'coinciden', s.n) order by s.rk), '[]'::jsonb)
                             from sug s where s.pagador = per.ced and s.rk <= 3))
           order by per.total desc, per.ced), '[]'::jsonb)
    from per
$function$;
revoke all on function public._consigna_personas(date, date, int, boolean) from public, anon, authenticated;

create or replace function public.consigna_por_listar()
returns jsonb
language plpgsql stable security definer set search_path to 'public'
as $function$
declare
  v_desde date := public._cartera_desde();
  v_hoy date := (now() at time zone 'America/Bogota')::date;
  v_plazo int := coalesce((select c.plazo_dias from public.liq_cartera_config c where c.id), 1);
begin
  if not (select public.es_admin()) then
    return jsonb_build_object('ok', false, 'error', 'Solo el administrador.');
  end if;
  if v_desde is null then
    return jsonb_build_object('ok', false, 'error', 'La cartera todavía no arranca: falta el día de arranque.');
  end if;
  return jsonb_build_object('ok', true, 'desde', v_desde,
    'reglas', (
      with uso as (select b.regla, count(*) as n, coalesce(sum(b.valor), 0)::bigint as total, max(b.fecha) as ultimo
                     from public._recaudos_cartera(v_desde) b where b.regla is not null group by b.regla)
      select coalesce(jsonb_agg(jsonb_build_object(
               'id', a.id, 'pagador', a.pagador, 'pagador_nombre', public._cartera_nombre(a.pagador),
               'conductor', a.conductor, 'conductor_nombre', public._cartera_nombre(a.conductor),
               'recaudo_id', a.recaudo_id,
               'deposito', (select jsonb_build_object('fecha', r.fecha, 'valor', r.valor)
                              from public.recaudos_banco r where r.id = a.recaudo_id),
               'desde', a.desde, 'hasta', a.hasta, 'nota', a.nota,
               'creado', to_char(a.creado_en at time zone 'America/Bogota', 'DD/MM/YYYY HH24:MI'),
               'depositos', coalesce(u.n, 0), 'total', coalesce(u.total, 0), 'ultimo', u.ultimo)
             order by (a.recaudo_id is not null), a.creado_en desc), '[]'::jsonb)
        from public.cartera_consigna_por a left join uso u on u.regla = a.id),
    'personas', public._consigna_personas(v_desde, v_hoy, v_plazo, true));
end $function$;
revoke all on function public.consigna_por_listar() from public, anon;
grant execute on function public.consigna_por_listar() to authenticated;

-- Para la tarjeta de Liquidaciones (rápido: sin sugerencias)
create or replace function public.consigna_por_resumen()
returns jsonb
language plpgsql stable security definer set search_path to 'public'
as $function$
declare v_desde date := public._cartera_desde(); v_p jsonb;
begin
  if not (select public.es_admin()) then
    return jsonb_build_object('ok', false, 'error', 'Solo el administrador.');
  end if;
  if v_desde is null then
    return jsonb_build_object('ok', false, 'error', 'La cartera todavía no arranca.');
  end if;
  v_p := public._consigna_personas(v_desde, null, null, false);
  return jsonb_build_object('ok', true,
    'reglas', (select count(*) from public.cartera_consigna_por where recaudo_id is null),
    'asignados', (select count(*) from public.cartera_consigna_por where recaudo_id is not null),
    'movido', (select coalesce(sum(b.valor), 0) from public._recaudos_cartera(v_desde) b where b.como <> 'PROPIO'),
    'personas', jsonb_array_length(v_p),
    'sin_asignar', (select coalesce(sum((e ->> 'total')::bigint), 0) from jsonb_array_elements(v_p) e));
end $function$;
revoke all on function public.consigna_por_resumen() from public, anon;
grant execute on function public.consigna_por_resumen() to authenticated;

-- Los depósitos de una cédula desde el arranque, con a quién se le abona cada uno
create or replace function public.consigna_por_depositos(p_cedula text)
returns jsonb
language plpgsql stable security definer set search_path to 'public'
as $function$
declare
  v_ced text := regexp_replace(coalesce(p_cedula, ''), '\D', '', 'g');
  v_desde date := public._cartera_desde();
begin
  if not (select public.es_admin()) then
    return jsonb_build_object('ok', false, 'error', 'Solo el administrador.');
  end if;
  if length(v_ced) < 5 then
    return jsonb_build_object('ok', false, 'error', 'Escribe la cédula completa.');
  end if;
  return jsonb_build_object('ok', true, 'cedula', v_ced, 'nombre', public._cartera_nombre(v_ced), 'desde', v_desde,
    'tiene_liquidaciones', exists (select 1 from public.liquidaciones l where l.conductor_cedula = v_ced and l.fecha >= v_desde),
    'depositos', (select coalesce(jsonb_agg(jsonb_build_object(
                    'id', b.id, 'fecha', b.fecha, 'valor', b.valor, 'a', b.ced,
                    'a_nombre', case when b.ced <> v_ced then public._cartera_nombre(b.ced) end,
                    'como', b.como, 'regla', b.regla) order by b.fecha desc, b.id desc), '[]'::jsonb)
                    from public._recaudos_cartera(v_desde) b
                   where b.pagador = v_ced and b.valor > 0));
end $function$;
revoke all on function public.consigna_por_depositos(text) from public, anon;
grant execute on function public.consigna_por_depositos(text) to authenticated;

-- Guardar: con p_recaudo_id es ESE depósito; sin él, la regla para todo lo de p_pagador (desde p_desde)
create or replace function public.consigna_por_guardar(p_pagador text, p_conductor text,
  p_recaudo_id bigint default null, p_desde date default null, p_nota text default null)
returns jsonb
language plpgsql security definer set search_path to 'public'
as $function$
declare
  v_pag text := nullif(regexp_replace(coalesce(p_pagador, ''), '\D', '', 'g'), '');
  v_con text := regexp_replace(coalesce(p_conductor, ''), '\D', '', 'g');
  v_nota text := nullif(left(btrim(coalesce(p_nota, '')), 300), '');
  v_ini date := public._cartera_desde();
  r record; v_id bigint;
begin
  if not (select public.es_admin()) then
    return jsonb_build_object('ok', false, 'error', 'Solo el administrador.');
  end if;
  if v_con !~ '^[0-9]{5,12}$' then
    return jsonb_build_object('ok', false, 'error', 'Elige el conductor.');
  end if;
  if not exists (select 1 from public.liquidaciones l where l.conductor_cedula = v_con) then
    return jsonb_build_object('ok', false, 'error', 'Ese conductor no tiene liquidaciones: la plata no tendría qué pagar.');
  end if;

  if p_recaudo_id is not null then
    select b.id, b.pagador, b.ced into r from public._recaudos_cartera(date '1900-01-01') b where b.id = p_recaudo_id;
    if r.id is null then
      return jsonb_build_object('ok', false, 'error', 'No encontré ese depósito del banco.');
    end if;
    if r.pagador is not distinct from v_con then
      -- Volver a dejarlo como estaba: es del mismo que consignó
      delete from public.cartera_consigna_por where recaudo_id = p_recaudo_id;
      return jsonb_build_object('ok', true, 'quitado', true);
    end if;
    insert into public.cartera_consigna_por (pagador, conductor, recaudo_id, nota)
    values (r.pagador, v_con, p_recaudo_id, v_nota)
    on conflict (recaudo_id) where recaudo_id is not null
      do update set conductor = excluded.conductor, nota = coalesce(excluded.nota, cartera_consigna_por.nota),
                    creado_en = now(), creado_por = auth.uid()
    returning id into v_id;
  else
    if v_pag is null or v_pag !~ '^[0-9]{5,12}$' then
      return jsonb_build_object('ok', false, 'error', 'Escribe la cédula de quien consigna.');
    end if;
    if v_pag = v_con then
      return jsonb_build_object('ok', false, 'error', 'Quien consigna y el conductor son la misma persona.');
    end if;
    -- Un conductor con sus propias liquidaciones no puede ceder TODO: sus días quedarían sin pagar
    if exists (select 1 from public.liquidaciones l where l.conductor_cedula = v_pag and l.fecha >= v_ini) then
      return jsonb_build_object('ok', false, 'error',
        'Esa cédula tiene sus propias liquidaciones: pasa depósito por depósito, no todos.');
    end if;
    insert into public.cartera_consigna_por (pagador, conductor, desde, nota)
    values (v_pag, v_con, p_desde, v_nota)
    on conflict (pagador, (coalesce(desde, date '1900-01-01'))) where recaudo_id is null
      do update set conductor = excluded.conductor, nota = coalesce(excluded.nota, cartera_consigna_por.nota),
                    creado_en = now(), creado_por = auth.uid()
    returning id into v_id;
  end if;
  return jsonb_build_object('ok', true, 'id', v_id,
    'depositos', (select count(*) from public._recaudos_cartera(v_ini) b where b.regla = v_id),
    'total', (select coalesce(sum(b.valor), 0) from public._recaudos_cartera(v_ini) b where b.regla = v_id));
exception when others then
  return jsonb_build_object('ok', false, 'error', 'No se pudo guardar: ' || SQLERRM);
end $function$;
revoke all on function public.consigna_por_guardar(text, text, bigint, date, text) from public, anon;
grant execute on function public.consigna_por_guardar(text, text, bigint, date, text) to authenticated;

