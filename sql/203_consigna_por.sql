-- 203_consigna_por.sql · QUIÉN CONSIGNA POR QUIÉN
-- "podemos poner los conductores que le liquido otra persona x que no es de la empresa" -> "si" a la
-- lista de "quién consigna por quién" en la app (24/11/2026).
--
-- EL PROBLEMA: el banco solo trae la cédula de QUIEN consigna (ref1 = cédula con ceros; ref2 vacía, no
-- trae el bus). Cuando otra persona paga por el conductor (un familiar, un conocido, otro conductor), la
-- plata entra con la cédula de esa persona: la cartera no se la abona al conductor y lo muestra en mora.
-- Comparado con los planos de contabilidad del 1 al 16/11: 25 depósitos así; 14 de ellos de 6 personas
-- que no aparecen en la app, por 5 conductores ($999.800). Contabilidad lo sabe por fuera.
--
-- LO QUE HACE:
--   1) cartera_consigna_por: las reglas que pone el administrador. Dos clases:
--        · REGLA: "todo lo que consigne la cédula X es del conductor Y" (desde/hasta opcionales).
--        · ASIGNADO: "este depósito del banco es del conductor Y" (uno solo; sirve también para la plata
--          que un conductor pone por un compañero, sin tocar el resto de sus depósitos).
--   2) _recaudos_cartera(desde): cada depósito del banco con la cédula a la que se le ABONA
--      (asignado > regla > la del banco). Sin reglas da lo mismo que recaudos_banco.cedula.
--   3) _cartera_movs (sql/154) y liquidaciones_planilla (sql/148) usan esa cédula en vez de r.cedula:
--      la cartera, el tablero, la mora, el pago de cada día y la planilla ven el depósito en el conductor.
--   4) cartera_conductor (sql/155) dice además qué pagos hizo otra persona por él y qué depósitos suyos
--      se pasaron a otro (solo administrador: el link público del conductor no muestra cédulas ajenas).
--   5) Para la pantalla (solo administrador): consigna_por_listar, consigna_por_depositos,
--      consigna_por_guardar, consigna_por_quitar y consigna_por_resumen.
--
-- Sin reglas, la cartera queda IDÉNTICA (se comprobó con la huella md5 antes y después).
--
-- DESHACER: volver a ejecutar _cartera_movs de sql/154, liquidaciones_planilla de sql/148 y
-- cartera_conductor de sql/155; luego
--   drop function public.consigna_por_resumen(); drop function public.consigna_por_listar();
--   drop function public.consigna_por_depositos(text);
--   drop function public.consigna_por_guardar(text, text, bigint, date, text);
--   drop function public.consigna_por_quitar(bigint);
--   drop function public._consigna_personas(date, date, int, boolean);
